`timescale 1ns / 1ps

// -----------------------------------------------------------------------------
// Module intennal and external signals
// -----------------------------------------------------------------------------
module clock_divider_TB();
  reg clk_fast, reset;
  wire clk_slow;

// -----------------------------------------------------------------------------
// Instantiate the design under test (DUT)
// -----------------------------------------------------------------------------
  clock_divider DUT_divider(
    .clk_in(clk_fast),
    .clk_out(clk_slow),
    .reset(reset),
    .ratio(32'd1_000_000) // 50Hz
  ); 

// -----------------------------------------------------------------------------
// Testbench behavior
// -----------------------------------------------------------------------------
  always #5 clk_fast = ~clk_fast; //50Mhz clock

  initial begin
    clk_fast=0; reset=0; #999996;
    reset=1; 
    #10000000;
    $stop;
  end

// -----------------------------------------------------------------------------
// Monitoring
// -----------------------------------------------------------------------------

endmodule
